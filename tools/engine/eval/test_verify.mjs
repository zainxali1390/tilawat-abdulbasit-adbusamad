// Step 12 functional tests: js/engine/verify.js (pure function, Node).   node test_verify.mjs
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
globalThis.window = undefined; await import(path.join(ROOT, 'js/engine/verify.js')); const V = globalThis.VERIFY;
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
const C = (code, inl, mel, agree, verse = 'none', ts = {start: 100, end: 120, clipA: 0, clipB: 20, src: 'landmarks'}) => ({code, lm: {inl, span: 15, k: 1, b: 100}, mel: {score: mel, k: 1, at: 100}, agree, verse, ts});
let d = V.decide([C('A', 9, 0.9, true), C('B', 2, 0.5, false)], []);
ok(d.level === 'confirmed' && d.top.code === 'A' && d.reasons[0].k === 'agree', 'confirmed: both alignments agree with >= 6 points');
d = V.decide([C('A', 5, 0.9, true)], []);
ok(d.level === 'high', 'high: agreement with 4-5 points');
d = V.decide([C('A', 3, 0.9, true, 'agree')], []);
ok(d.level === 'high', 'high: agreement with 3 points and the verses agree');
d = V.decide([C('A', 3, 0.7, true)], []);
ok(d.level === 'none' && d.reasons[0].k === 'noEvidence', 'none: agreement on only 3 points (measured: 1 right, 26 wrong)');
d = V.decide([C('A', 9, 0.9, true, 'contradict')], []);
ok(d.level === 'possible' && d.reasons.some(r => r.k === 'verseContradict'), 'a contradiction by the verses lowers a strong match to possible');
d = V.decide([C('A', 4, 0.85, false)], []);
ok(d.level === 'possible', 'possible: strong melody with landmark support');
d = V.decide([C('A', 1, 0.3, false)], [{code: 'A', level: 'possible', start: 50}]);
ok(d.level === 'possible' && d.top.ts.src === 'finder', "possible: the finder's own possible, with the finder's time");
d = V.decide([C('B', 5, 0.95, true), C('A', 2, 0.4, false)], [{code: 'A', level: 'confirmed', start: 77, end: 97, clipA: 0, clipB: 20}]);
ok(d.level === 'confirmed' && d.top.code === 'A' && d.top.ts.start === 77, "the finder's confirmed result wins over a weaker engine match, with its time");
d = V.decide([C('A', 12, 0.9, true), C('A2', 8, 0.88, true), C('B', 3, 0.6, false)], []);
ok(d.level === 'confirmed' && d.copies.length === 1 && d.copies[0].code === 'A2', 'a second recording on the same line is listed as a copy, not a rival');
d = V.decide([], [], {voice: {verdict: 'unlike'}});
ok(d.level === 'none' && d.reasons.some(r => r.k === 'voiceUnlike'), 'no match: the voice note is added when the voice is unlike');
d = V.decide([C('A', 1, 0.2, false)], [], {voice: {verdict: 'no-objection'}});
ok(d.level === 'none' && !d.reasons.some(r => r.k === 'voiceUnlike'), 'no match: no voice note otherwise');
ok(V.describe({k: 'agree', inl: 9, span: 15, mel: 90}).includes('9 matching points') && V.describe({k: 'voiceUnlike'}).includes('another reciter'), 'reasons have English text');
console.log(fails ? fails + ' FAILED' : 'all passed'); process.exit(fails ? 1 : 0);
